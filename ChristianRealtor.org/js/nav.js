/* Site navigation behavior, shared by every page.
   The menu works without this file (CSS hover/focus dropdowns, a #sn-panel link, and <details> sections).
   This adds menu state for assistive technology, keyboard support, and focus management.
   Markup is generated by site-tools/sync-nav.py (see CLAUDE.md). */
(function () {
  var doc = document;
  var root = doc.documentElement;
  var header = doc.querySelector('.sn-header');
  if (!header) return;

  /* ---------- Mobile panel ---------- */
  var toggle = header.querySelector('.sn-toggle');
  var panel = doc.getElementById('sn-panel');
  var closeLink = panel ? panel.querySelector('.sn-close') : null;
  var desktop = window.matchMedia('(min-width: 1100px)');

  function focusables() {
    return Array.prototype.filter.call(
      panel.querySelectorAll('a[href], button, summary'),
      function (el) { return el.offsetWidth > 0 || el.offsetHeight > 0; }
    );
  }

  function openPanel() {
    panel.classList.add('sn-open');
    toggle.setAttribute('aria-expanded', 'true');
    root.classList.add('sn-locked');
    closeLink.focus();
  }

  function closePanel(returnFocus) {
    if (!panel.classList.contains('sn-open')) return;
    panel.classList.remove('sn-open');
    toggle.setAttribute('aria-expanded', 'false');
    root.classList.remove('sn-locked');
    if (returnFocus !== false) toggle.focus();
  }

  if (toggle && panel && closeLink) {
    [toggle, closeLink].forEach(function (el) {
      el.setAttribute('role', 'button');
      el.addEventListener('keydown', function (e) {
        if (e.key === ' ' || e.key === 'Spacebar') { e.preventDefault(); el.click(); }
      });
    });
    toggle.setAttribute('aria-expanded', 'false');

    toggle.addEventListener('click', function (e) {
      e.preventDefault();
      if (panel.classList.contains('sn-open')) closePanel(); else openPanel();
    });
    closeLink.addEventListener('click', function (e) {
      e.preventDefault();
      closePanel();
    });

    panel.addEventListener('keydown', function (e) {
      if (e.key === 'Escape' || e.key === 'Esc') { e.preventDefault(); closePanel(); return; }
      if (e.key !== 'Tab') return;
      var items = focusables();
      if (!items.length) return;
      var first = items[0], last = items[items.length - 1];
      if (e.shiftKey && doc.activeElement === first) { e.preventDefault(); last.focus(); }
      else if (!e.shiftKey && doc.activeElement === last) { e.preventDefault(); first.focus(); }
    });

    /* Following a link (including same-page anchors) closes the panel */
    panel.addEventListener('click', function (e) {
      var link = e.target.closest('a[href]');
      if (link && link !== closeLink) closePanel(false);
    });

    var onResize = function () { if (desktop.matches) closePanel(false); };
    if (desktop.addEventListener) desktop.addEventListener('change', onResize);
    else if (desktop.addListener) desktop.addListener(onResize);
  }

  /* ---------- Desktop dropdowns ---------- */
  var drops = Array.prototype.slice.call(header.querySelectorAll('.sn-dd'));

  function setOpen(drop, open) {
    drop.classList.toggle('sn-open', open);
    var control = drop.querySelector('[aria-controls]');
    if (control) control.setAttribute('aria-expanded', open ? 'true' : 'false');
  }

  drops.forEach(function (drop) {
    var control = drop.querySelector('button[aria-controls]');
    if (!control) return;

    control.addEventListener('click', function () {
      var open = !drop.classList.contains('sn-open');
      drops.forEach(function (other) { if (other !== drop) setOpen(other, false); });
      setOpen(drop, open);
      /* After a click closes the menu, keep it closed even though the pointer or focus is still inside */
      drop.classList.toggle('sn-hush', !open);
    });

    drop.addEventListener('keydown', function (e) {
      if (e.key === 'Escape' || e.key === 'Esc') {
        setOpen(drop, false);
        drop.classList.add('sn-hush');
        control.focus();
      }
    });

    drop.addEventListener('mouseleave', function () {
      drop.classList.remove('sn-hush');
      if (!drop.contains(doc.activeElement)) setOpen(drop, false);
    });

    drop.addEventListener('focusout', function (e) {
      if (!drop.contains(e.relatedTarget)) {
        drop.classList.remove('sn-hush');
        setOpen(drop, false);
      }
    });
  });

  doc.addEventListener('click', function (e) {
    drops.forEach(function (drop) { if (!drop.contains(e.target)) setOpen(drop, false); });
  });

  /* ---------- Text Luke measurement (GA4 event, not a conversion) ----------
     Links that already carry data-track (for example on /sign) are measured by their page's own script. */
  doc.addEventListener('click', function (e) {
    var link = e.target.closest ? e.target.closest('a[href^="sms:"]') : null;
    if (!link || link.hasAttribute('data-track')) return;
    if (typeof window.gtag === 'function') {
      window.gtag('event', 'text_luke_click', {
        link_location: link.getAttribute('data-cta') || '',
        page_path: window.location.pathname
      });
    }
  });
})();
