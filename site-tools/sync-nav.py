NAV_RE = re.compile(r"<!-- SITE NAV:START.*?<!-- SITE NAV:END -->", re.S)
ASSETS_RE = re.compile(r"<!-- SITE NAV ASSETS:START.*?<!-- SITE NAV ASSETS:END -->", re.S)


def pages():
    for path in sorted(SITE.rglob("*.html")):
        rel = path.relative_to(SITE).as_posix()
        if rel.startswith(("admin/", "netlify/")):
            continue
        yield rel, path


def main():
    check = "--check" in sys.argv
    stale, missing, updated = [], [], 0
    for rel, path in pages():
        text = path.read_text(encoding="utf-8")
        if "<!-- SITE NAV:START" not in text:
            if "<body" in text and "<nav" in text:
                missing.append(rel)
            continue
        if not ASSETS_RE.search(text):
            missing.append(rel + " (assets markers)")
            continue
        new = NAV_RE.sub(lambda m: render_nav(page_key(rel, text)), text, count=1)
        new = ASSETS_RE.sub(lambda m: ASSETS, new, count=1)
        if new != text:
            if check:
                stale.append(rel)
            else:
                path.write_text(new, encoding="utf-8")
                updated += 1
    if missing:
        print("Pages with a menu but no SITE NAV markers:", *missing, sep="\n  ")
    if check:
        print("Out of date:", *stale, sep="\n  ") if stale else print("All menus are up to date.")
        sys.exit(1 if stale or missing else 0)
    print(f"Updated {updated} page(s).")


if __name__ == "__main__":
    main()
