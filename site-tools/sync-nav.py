def page_key(rel_path, text):
    if rel_path in PAGE_KEY_OVERRIDES:
        return PAGE_KEY_OVERRIDES[rel_path]
    m = re.search(r'<link rel="canonical" href="https://christianrealtor\.org([^"]*)"', text)
    if m:
        return m.group(1) or "/"
    return "/" + rel_path


def cur(url, key):
    return ' aria-current="page"' if url == key else ""


def links(items, key, indent):
    pad = " " * indent
    return "\n".join(f'{pad}<li><a href="{u}"{cur(u, key)}>{t}</a></li>' for t, u in items)


